const dict: Record<GameLanguage, Translation> = {
  vi: baseDict.vi,
  en: baseDict.en,
  ko,
  ja,
  fr,
};

export function detectDeviceLanguage(): GameLanguage {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (GAME_LANGUAGES.some(({ code }) => code === saved)) {
    return saved as GameLanguage;
  }
  const language = (navigator.language || navigator.languages?.[0] || "vi").toLowerCase();
  if (language.startsWith("vi")) return "vi";
  if (language.startsWith("ko")) return "ko";
  if (language.startsWith("ja")) return "ja";
  if (language.startsWith("fr")) return "fr";
  return "en";
}

export function saveLanguage(language: GameLanguage) {
  localStorage.setItem(STORAGE_KEY, language);
}

export function translate(language: GameLanguage, key: GameTextKey) {
  return dict[language]?.[key] || dict.en[key] || dict.vi[key] || key;
}
